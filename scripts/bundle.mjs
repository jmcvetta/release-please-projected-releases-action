/**
 * bundle builds the committed action artifact, dist/index.mjs.
 *
 * A JavaScript action runs the file the caller checked out, with no install
 * step, so the whole dependency tree has to be in that file. release-please
 * and octokit make it about two and a half megabytes, which is the price of
 * an action that starts in a second rather than after an `npm ci`.
 *
 * The banner names release-please's version and nothing about this package's.
 * That is deliberate: release-please bumps package.json on its release pull
 * request, so a banner carrying the package version would make dist/index.mjs
 * stale on exactly that pull request, and CI's staleness check would fail the
 * one merge that cuts a tag. The tag says which version this is; the file does
 * not need to. What the file cannot say any other way is which release-please
 * it wraps, since the whole tool is a view over one pinned version of it.
 *
 * The banner is also load-bearing for a second reason. esbuild rewrites CommonJS `require` calls it
 * can resolve, and leaves the rest to a stub that throws "Dynamic require of
 * \"os\" is not supported" — which is exactly what happens without it, deep
 * inside release-please's logger. Defining `require` from `createRequire`
 * gives that stub something real to fall back to; builtins resolve, and
 * nothing else is left unbundled to resolve.
 */

import { build } from "esbuild";
import { cpSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";

const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));

const result = await build({
  entryPoints: ["src/index.ts"],
  outfile: "dist/index.mjs",
  bundle: true,
  platform: "node",
  format: "esm",
  // Matches `runs.using: node24` in action.yml.
  target: "node24",
  sourcemap: false,
  // Collected at the end of the file rather than dropped. dist/index.mjs is a
  // committed, distributed artifact carrying release-please and its
  // dependency tree, and their licenses require their notices to travel with
  // them.
  legalComments: "eof",
  banner: {
    js: [
      "// Generated by scripts/bundle.mjs. Do not edit; run `npm run build`.",
      `// Bundled release-please ${pkg.dependencies["release-please"]}.`,
      'import { createRequire as __createRequire } from "node:module";',
      'import { fileURLToPath as __fileURLToPath } from "node:url";',
      'import { dirname as __pathDirname } from "node:path";',
      "const require = __createRequire(import.meta.url);",
      // The changelog preset reads its Handlebars templates at run time with
      // `resolve(__dirname, "./templates/...")`, and an ESM bundle has no
      // __dirname. Defining it as the bundle's own directory works because
      // the templates are copied next to the bundle below -- and because
      // those four reads are the only __dirname in the whole bundle, which
      // is checked rather than assumed.
      "const __filename = __fileURLToPath(import.meta.url);",
      "const __dirname = __pathDirname(__filename);",
    ].join("\n"),
  },
  metafile: true,
});

// The changelog preset's templates, beside the bundle, where the __dirname
// defined in the banner points. Without them the bundle loads, runs, walks
// every commit, and dies only when it renders a changelog -- which is to say,
// only on a pull request that actually releases something.
const require2 = createRequire(import.meta.url);
const preset = require2.resolve(
  "conventional-changelog-conventionalcommits/package.json",
);
cpSync(
  new URL("./templates/", `file://${preset}`),
  new URL("../dist/templates/", import.meta.url),
  { recursive: true },
);

const bytes = Object.values(result.metafile.outputs)[0]?.bytes ?? 0;
process.stdout.write(`dist/index.mjs  ${(bytes / 1024 / 1024).toFixed(1)}mb\n`);
