/**
 * bundle builds the committed action artifact, dist/index.mjs.
 *
 * A JavaScript action runs the file the caller checked out, with no install
 * step, so the whole dependency tree has to be in that file. release-please
 * and octokit make it about two and a half megabytes, which is the price of
 * an action that starts in a second rather than after an `npm ci`.
 *
 * The banner is load-bearing. esbuild rewrites CommonJS `require` calls it
 * can resolve, and leaves the rest to a stub that throws "Dynamic require of
 * \"os\" is not supported" — which is exactly what happens without it, deep
 * inside release-please's logger. Defining `require` from `createRequire`
 * gives that stub something real to fall back to; builtins resolve, and
 * nothing else is left unbundled to resolve.
 */

import { build } from "esbuild";
import { readFileSync } from "node:fs";

const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));

const result = await build({
  entryPoints: ["src/index.ts"],
  outfile: "dist/index.mjs",
  bundle: true,
  platform: "node",
  format: "esm",
  // Matches `runs.using: node24` in action.yml.
  target: "node24",
  sourcemap: false,
  legalComments: "none",
  banner: {
    js: [
      "// Generated by scripts/bundle.mjs. Do not edit; run `npm run build`.",
      `// projected-releases ${pkg.version}, release-please ${pkg.dependencies["release-please"]}`,
      'import { createRequire as __createRequire } from "node:module";',
      "const require = __createRequire(import.meta.url);",
    ].join("\n"),
  },
  metafile: true,
});

const bytes = Object.values(result.metafile.outputs)[0]?.bytes ?? 0;
process.stdout.write(`dist/index.mjs  ${(bytes / 1024 / 1024).toFixed(1)}mb\n`);
